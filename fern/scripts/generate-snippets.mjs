// Generates the data-driven tables (models, telephony pricing, error codes)
// as Markdown snippets from the committed API snapshots in fern/snapshots/.
//
// Fern pages include them with <Markdown src="/docs/snippets/generated/…" />.
// Refresh the snapshots first with: node fern/scripts/sync-api.mjs
// Everything is committed — the docs build never depends on the API being up.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SNAPSHOTS = join(ROOT, "snapshots");
const OUT = join(ROOT, "docs", "snippets", "generated");
const DASH = "—";

/** @param {string} name */
async function snapshot(name) {
  return JSON.parse(await readFile(join(SNAPSHOTS, name), "utf8"));
}

/** Escape characters that break Markdown table cells. @param {unknown} v */
function cell(v) {
  if (v === null || v === undefined || v === "") return DASH;
  return String(v).replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

/** @param {string[]} header @param {unknown[][]} rows */
function table(header, rows) {
  const line = (cells) => `| ${cells.map(cell).join(" | ")} |`;
  return [line(header), `| ${header.map(() => "---").join(" | ")} |`, ...rows.map(line)].join("\n");
}

const files = new Map();
/** @param {string} name @param {string} body */
function emit(name, body) {
  files.set(`${name}.mdx`, `{/* Generated by fern/scripts/generate-snippets.mjs — do not edit. */}\n\n${body.trim()}\n`);
}

// ── Models ─────────────────────────────────────────────────────────────────

function llmTable(providers, showCapabilities) {
  return providers
    .map((p) => {
      const header = ["Model", ...(showCapabilities ? ["Context", "Description"] : []), "Input / 1M tokens", "Output / 1M tokens"];
      const rows = p.models.map((m) => [
        `\`${m.modelId}\``,
        ...(showCapabilities
          ? [m.contextWindow ? `${(m.contextWindow / 1000).toFixed(0)}K` : DASH, m.description]
          : []),
        m.pricing?.inputPer1mTokensDisplay,
        m.pricing?.outputPer1mTokensDisplay,
      ]);
      return (providers.length > 1 ? `#### ${p.displayName}\n\n` : "") + table(header, rows);
    })
    .join("\n\n");
}

const TTS_FEATURES = [
  ["emotion", "Emotion"],
  ["speedControl", "Speed"],
  ["volumeControl", "Volume"],
  ["speakerBoost", "Speaker Boost"],
  ["style", "Style"],
];
const STT_FEATURES = [
  ["streaming", "Streaming"],
  ["diarization", "Diarization"],
  ["telephony", "Telephony"],
  ["noiseHandling", "Noise Handling"],
  ["multilingual", "Multilingual"],
];

function features(caps, keys) {
  if (!caps) return DASH;
  const on = keys.filter(([k]) => caps[k]).map(([, label]) => label);
  return on.length ? on.join(", ") : DASH;
}

function speechTable(providers, showCapabilities, rateKey, rateLabel, featureKeys) {
  return providers
    .map((p) => {
      const header = ["Model", ...(showCapabilities ? ["Languages", "Features"] : []), rateLabel];
      const rows = p.models.map((m) => [
        `\`${m.modelId}\``,
        ...(showCapabilities ? [m.languages?.length ?? DASH, features(m.capabilities, featureKeys)] : []),
        m.pricing?.[rateKey],
      ]);
      return (providers.length > 1 ? `#### ${p.displayName}\n\n` : "") + table(header, rows);
    })
    .join("\n\n");
}

async function generateModels() {
  // Two datasets: the full catalog, and the flow-builder subset (use_case=flow)
  const [all, flow] = await Promise.all([snapshot("models.json"), snapshot("models-flow.json")]);

  const render = (cat, providers, showCapabilities) => {
    if (cat === "llm") return llmTable(providers, showCapabilities);
    if (cat === "tts") return speechTable(providers, showCapabilities, "ratePer1kCharsDisplay", "Per 1K characters", TTS_FEATURES);
    return speechTable(providers, showCapabilities, "ratePerMinuteDisplay", "Per minute", STT_FEATURES);
  };

  for (const cat of ["llm", "tts", "stt"]) {
    // <ModelTable category="…" /> — all providers, no capabilities
    emit(`models-${cat}`, render(cat, all[cat], false));
    // <ModelTable category="…" provider="…" useCase="flow" showCapabilities />
    for (const p of flow[cat]) {
      emit(`models-${cat}-${p.provider}`, render(cat, [p], true));
    }
  }
}

// ── Telephony pricing ──────────────────────────────────────────────────────

const PROVIDER_NAMES = { twilio: "Twilio", sip: "SIP Trunking", webrtc: "WebRTC", whatsapp: "WhatsApp" };


async function generatePricing() {
  const data = await snapshot("pricing.json");

  // The API prices inbound and outbound separately (rates.perMinuteInbound /
  // rates.perMinuteOutbound) and ships its own display string, so no rounding
  // happens here. A missing rate renders as a dash.
  const perMinute = (rate) => (rate ? (rate.microcents === 0 ? "Free" : rate.display) : DASH);
  emit(
    "pricing-telephony",
    table(
      ["Provider", "Inbound / min", "Outbound / min"],
      data.telephony.map((t) => [
        PROVIDER_NAMES[t.provider] ?? t.provider,
        perMinute(t.rates.perMinuteInbound),
        perMinute(t.rates.perMinuteOutbound),
      ]),
    ),
  );

  emit(
    "pricing-phone-numbers",
    `${table(["Fee", "Amount"], [["**Purchase**", `${data.phoneNumbers.startingFrom.display} one-time`]])}\n\n${data.phoneNumbers.note}`,
  );

  emit(
    "pricing-recording-storage",
    `${table(["Fee", "Amount"], [["**Storage**", `${data.recordingStorage.perGbMonth.display} / GB / month`]])}\n\n${data.recordingStorage.note}`,
  );
}

// ── Error codes ────────────────────────────────────────────────────────────

const formatCategory = (cat) => cat.split("_").map((w) => w[0].toUpperCase() + w.slice(1)).join(" ");

async function generateErrors() {
  const data = await snapshot("errors.json");

  const groups = new Map();
  for (const e of data.errorCodes) {
    if (!groups.has(e.category)) groups.set(e.category, []);
    groups.get(e.category).push(e);
  }
  const sections = [...groups.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([category, codes]) => {
      codes.sort((a, b) => a.status - b.status || a.code.localeCompare(b.code));
      const rows = codes.map((e) => [`\`${e.code}\``, e.status, `**${e.title}** — ${e.description}`]);
      return `## ${formatCategory(category)}\n\n${table(["Code", "Status", "Description"], rows)}`;
    });

  if (data.fieldErrorCodes.length > 0) {
    const rows = [...data.fieldErrorCodes]
      .sort((a, b) => a.code.localeCompare(b.code))
      .map((e) => [`\`${e.code}\``, e.description]);
    sections.push(
      "## Field Validation\n\n" +
        "Field-level errors appear in the `errors[]` array when the response code is `validation_failed`. " +
        "Each entry includes the field name, a machine-readable code, and a human-readable message.\n\n" +
        table(["Code", "Description"], rows),
    );
  }

  emit("error-codes", sections.join("\n\n"));
}

// ── Main ───────────────────────────────────────────────────────────────────

await Promise.all([generateModels(), generatePricing(), generateErrors()]);
await mkdir(OUT, { recursive: true });
for (const [name, body] of files) await writeFile(join(OUT, name), body);
console.log(`wrote ${files.size} snippets to ${OUT}`);
